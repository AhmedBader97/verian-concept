/**
 * Builds the dot-matrix world map used by the home page.
 *
 * Dots sit on a regular grid in Equal Earth projected space (an equal-area
 * projection, so no continent is visually inflated). Land polygons (Natural
 * Earth 1:50m, already split at the antimeridian) are projected once, and each
 * grid point is tested with a planar even-odd rule against rings whose bounding
 * box contains it. Output coordinates are normalised to [0, 1] inside a crop.
 *
 * Usage: node scripts/world-dots.mjs
 */
import { readFileSync, writeFileSync } from "node:fs";
import { geoEqualEarthRaw } from "d3-geo";
import { feature } from "topojson-client";

const land50 = JSON.parse(readFileSync(new URL("../node_modules/world-atlas/land-50m.json", import.meta.url)));
const land = feature(land50, land50.objects.land);

const DEG = Math.PI / 180;
const raw = geoEqualEarthRaw;

// Crop: drop Antarctica and the far Arctic for a compact, readable map.
const LAT_MIN = -57;
const LAT_MAX = 74;
const X_MAX = raw(Math.PI, 0)[0];
const Y_MAX = raw(0, LAT_MAX * DEG)[1];
const Y_MIN = raw(0, LAT_MIN * DEG)[1];
const bounds = { xMin: -X_MAX, xMax: X_MAX, yMin: Y_MIN, yMax: Y_MAX, latMin: LAT_MIN, latMax: LAT_MAX };

// Project every land ring into raw Equal Earth space once, with a bounding box.
const rings = [];
for (const f of land.features ?? [land]) {
  const geom = f.geometry ?? f;
  const polys = geom.type === "Polygon" ? [geom.coordinates] : geom.coordinates;
  for (const poly of polys) {
    for (const ring of poly) {
      const pts = ring.map(([lon, lat]) => raw(lon * DEG, lat * DEG));
      const xs = pts.map((p) => p[0]);
      const ys = pts.map((p) => p[1]);
      rings.push({ pts, x0: Math.min(...xs), x1: Math.max(...xs), y0: Math.min(...ys), y1: Math.max(...ys) });
    }
  }
}

function onLand(x, y) {
  let inside = false;
  for (const r of rings) {
    if (x < r.x0 || x > r.x1 || y < r.y0 || y > r.y1) continue;
    const p = r.pts;
    for (let i = 0, j = p.length - 1; i < p.length; j = i++) {
      const [xi, yi] = p[i];
      const [xj, yj] = p[j];
      if (yi > y !== yj > y && x < ((xj - xi) * (y - yi)) / (yj - yi) + xi) inside = !inside;
    }
  }
  return inside;
}

const norm = (x, y) => [(x - bounds.xMin) / (bounds.xMax - bounds.xMin), (bounds.yMax - y) / (bounds.yMax - bounds.yMin)];

function dots(spacing, box = null) {
  const out = [];
  const x0 = box ? box.x0 : bounds.xMin;
  const x1 = box ? box.x1 : bounds.xMax;
  const y0 = box ? box.y0 : bounds.yMin;
  const y1 = box ? box.y1 : bounds.yMax;
  let row = 0;
  for (let y = y1; y >= y0; y -= spacing, row++) {
    const offset = row % 2 ? spacing / 2 : 0; // hex-like stagger reads more organically
    for (let x = x0 + offset; x <= x1; x += spacing) {
      if (Math.abs(x) > X_MAX) continue;
      if (!onLand(x, y)) continue;
      const [nx, ny] = norm(x, y);
      out.push(Math.round(nx * 10000) / 10000, Math.round(ny * 10000) / 10000);
    }
  }
  return out;
}

/**
 * A region box centred on a lon/lat, `span` degrees of latitude tall. Boxes are
 * square in normalised coordinates, which makes their real aspect equal to the
 * full map's, so zooming is a uniform scale with no distortion or letterboxing.
 */
function regionBox(lon, lat, latSpan) {
  const [cx, cy] = norm(...raw(lon * DEG, lat * DEG));
  const [, yTop] = norm(...raw(lon * DEG, (lat + latSpan / 2) * DEG));
  const [, yBot] = norm(...raw(lon * DEG, (lat - latSpan / 2) * DEG));
  const h = Math.abs(yBot - yTop);
  const nbox = [cx - h / 2, cy - h / 2, cx + h / 2, cy + h / 2];
  // Back to raw projected units for dot generation.
  const toRawX = (nx) => bounds.xMin + nx * (bounds.xMax - bounds.xMin);
  const toRawY = (ny) => bounds.yMax - ny * (bounds.yMax - bounds.yMin);
  return {
    nbox,
    raw: { x0: toRawX(nbox[0]), x1: toRawX(nbox[2]), y0: toRawY(nbox[3]), y1: toRawY(nbox[1]) },
  };
}

function sized(target, box) {
  // Dot count scales with 1/spacing^2, so two passes land close to the target.
  let spacing = 0.04;
  let d = dots(spacing, box);
  for (let pass = 0; pass < 2; pass++) {
    spacing *= Math.sqrt(d.length / 2 / target);
    d = dots(spacing, box);
  }
  return { spacing, dots: d };
}

const regions = {
  europe: regionBox(9, 50, 30),
  apac: regionBox(136, -20, 56),
  northAmerica: regionBox(-93, 39, 36),
};

const world = sized(3600, null);
const out = {
  note: "Generated by scripts/world-dots.mjs from Natural Earth 1:50m land (world-atlas). Equal Earth projection, normalised to the crop in `bounds`.",
  bounds,
  aspect: (bounds.xMax - bounds.xMin) / (bounds.yMax - bounds.yMin),
  world: world.dots,
  regions: {},
};
for (const [name, region] of Object.entries(regions)) {
  // Same visual density as the world map: a fixed number of dot rows per box.
  const rows = 62;
  const r = { dots: dots((region.raw.y1 - region.raw.y0) / rows, region.raw) };
  out.regions[name] = { box: region.nbox.map((v) => Math.round(v * 10000) / 10000), dots: r.dots };
  console.log(`${name}: ${r.dots.length / 2} dots`);
}
console.log(`world: ${world.dots.length / 2} dots, aspect ${out.aspect.toFixed(4)}`);
writeFileSync(new URL("../src/data/world-dots.json", import.meta.url), JSON.stringify(out));
